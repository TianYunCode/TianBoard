#pragma once

/// @brief 画两笔→擦掉一段→撤销还原→重做→存盘冷读的自检入口。
namespace EraserSelfTest
{
    /**
     * @brief 在真实可撤销的场景里走一遍"用橡皮擦掉一笔的中段"。
     *
     * 详细说明：橡皮是画板上用得最多的工具之一，却从没被任何用例跑过——擦除不是"删掉整个图元"，
     * 而是把命中的每一块笔迹多边形按擦除带切开、用剩下的残片顶替原图元（`eraseLineTo`），
     * 再把这一动的removed/added 合成**一条**撤销命令。这里量四件界面上看得见的事：
     * ① 擦除带覆盖到的地方确实没有几何了（用多边形 `containsPoint` 判，不用包围盒），
     * 而带的两头与另一笔完全不受影响；② 抬一次笔只压一条撤销命令，撤销一次就得把整段擦除
     * 原样还回来、重做又没掉；③ 擦完存盘、绕开场景缓存冷读回来，盘上的那一页必须还是擦过的
     * 样子（漏掉这一步的话"屏幕上看没了、下次打开又长回来"是界面上查不出来的）；
     * ④ 笔迹组的条数不被擦除改写。临时文档自建自删，跑用例时那是沙箱目录。
     *
     * @return 不一致的条数；0 表示通过。
     */
    int run();
} // namespace EraserSelfTest
