#pragma once

/// @brief 页面操作之后"内存里的这一页"与"盘上的这一页"是否还一致的自检入口。
namespace PageOperationsSelfTest
{
    /**
     * @brief 在画板真实的文档上依次做新增页、复制页、移动页、删除页，每一步都拿盘上冷读来对账。
     *
     * 详细说明：页面操作同时牵着三样东西——`pageNNN.svg` 的改名、场景缓存里的索引搬移、
     * 图元资源文件的复制。任何一处错位都不会报错，只表现为"某一页变成了另一页"或者
     * "这一页的东西没了"，而这正是最难被用户发现、最难被测试覆盖的数据问题。
     * 每步之后的判据有三条：一是内存里的这一页（场景缓存直接拿）与盘上的这一页
     * （绕开缓存，读页文件重建场景）摊出来的内容清单必须逐项相同；二是**资源归属**——
     * 每一份包内文件（位图按 UUID 命名）只许属于一页，且必须真的在盘上。第一条看不出
     * "两页共用同一份文件"：像素指纹一样、内容一样，只有副本被删掉时原件的图才跟着没，
     * 所以钉复制这条路的承重墙必须是第二条。三是画板容器里那份**缩略图列表**与页数一样多、
     * 每一页都有一张图、副本的图与原件相同（翻页条与文档库看得见的那一层）。
     * 临时文档自建自删，用户数据不碰。
     *
     * @return 不一致的条数；0 表示通过。
     */
    int run();
} // namespace PageOperationsSelfTest
